import fs from 'node:fs';
import {chromium} from 'playwright';
import assert from 'node:assert/strict';
const base='http://sign-v1.100-110-241-2.sslip.io';
const credential=JSON.parse(fs.readFileSync('chief/deploy/secrets/staff.json'));
const shots=process.env.SHOTS || '/Users/dano/code/chief-dealroom/docs/status/shots';fs.mkdirSync(shots,{recursive:true});
const browser=await chromium.launch({headless:true});
try {
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 page.on('pageerror',error=>console.error('PAGE',error.message));
 page.on('response',r=>{if(r.status()>=400)console.error('HTTP',r.status(),new URL(r.url()).pathname)});
 await page.goto(`${base}/signin`);
 await page.getByLabel('Email',{exact:true}).fill('sender@amforge.test');
 await page.getByLabel('Password',{exact:true}).fill(process.env.STAFF_PASSWORD);
 await page.getByRole('button',{name:'Sign In',exact:true}).click();
 await page.waitForURL(url=>!url.pathname.includes('/signin'));
 await page.goto(`${base}/t/${credential.teamUrl}/documents`,{waitUntil:'networkidle'});
 await page.screenshot({path:`${shots}/A-envelopes-topbar.png`,fullPage:true});
 assert.ok((await page.locator('body').innerText()).includes('Documents'));
 await page.goto(`${base}/t/${credential.teamUrl}/documents?layout=sidebar`,{waitUntil:'networkidle'});
 await page.screenshot({path:`${shots}/A-envelopes-sidebar.png`,fullPage:true});
 await page.goto(`${base}/t/${credential.teamUrl}/documents?layout=topbar`,{waitUntil:'networkidle'});
 const {PDFDocument,StandardFonts,rgb}=await import('@cantoo/pdf-lib');
 const pdf=await PDFDocument.create();const sheet=pdf.addPage([595,842]);const font=await pdf.embedFont(StandardFonts.Helvetica);
 sheet.drawText('AmForge | Confidential agreement',{x:60,y:740,size:22,font,color:rgb(.12,.18,.3)});
 sheet.drawText('Signature acceptance fixture. Two signers, one canonical sealed PDF.',{x:60,y:690,size:11,font});
 const payload={type:'DOCUMENT',title:'AmForge agreement — field placement',recipients:[1,2].map(i=>({email:`review-signer${i}@amforge.test`,name:`Reviewer ${i}`,role:'SIGNER',fields:[{identifier:'agreement.pdf',type:'SIGNATURE',fieldMeta:{type:'signature'},page:1,positionX:10,positionY:30+i*20,width:40,height:8}]}))};
 const form=new FormData();form.append('payload',JSON.stringify(payload));form.append('files',new File([await pdf.save()],'agreement.pdf',{type:'application/pdf'}));
 const created=await fetch(`${base}/api/v2/envelope/create`,{method:'POST',headers:{Authorization:`Bearer ${credential.token}`},body:form});assert.equal(created.status,200);const {id}=await created.json();
 await page.goto(`${base}/t/${credential.teamUrl}/documents/${id}/edit`,{waitUntil:'networkidle'});
 await page.getByRole('button',{name:'Add Fields',exact:true}).last().click();
 await page.waitForTimeout(1200);
 await page.screenshot({path:`${shots}/A-editor-fields.png`,fullPage:true});
 console.log('EDITOR_TEXT', (await page.locator('body').innerText()).slice(0,900));
 const sent=await fetch(`${base}/api/v2/envelope/distribute`,{method:'POST',headers:{Authorization:`Bearer ${credential.token}`,'Content-Type':'application/json'},body:JSON.stringify({envelopeId:id,meta:{distributionMethod:'NONE'}})});assert.equal(sent.status,200);const recipients=(await sent.json()).recipients;
 const recipientPage=await browser.newPage({viewport:{width:1440,height:1000}});
 await recipientPage.goto(`${base}/sign/${recipients[0].token}`,{waitUntil:'networkidle'});await recipientPage.screenshot({path:`${shots}/A-signing.png`,fullPage:true});
 assert.ok(!(await recipientPage.locator('body').innerText()).includes('Documenso'));
 console.log('PASS staff login, both layouts, native editor, recipient branding screenshots');
} finally {await browser.close()}
